export const PROMPT_SETS: PromptSet[] = DEF.map((s) => ({
  id: s.id,
  name: s.name,
  desc: s.desc,
  color: s.color,
  group: s.group ?? "広げる",
  items: s.items.map(([name, question], i) => ({ id: `${s.id}-${i + 1}`, set: s.id, setName: s.name, name, question, color: s.color })),
}));
export const PROMPT_ITEMS: PromptItem[] = PROMPT_SETS.flatMap((s) => s.items);
export const PROMPT_BY_ID: Record<string, PromptItem> = Object.fromEntries(PROMPT_ITEMS.map((p) => [p.id, p]));
