export interface Hexagram {
  id: string; // h1 〜 h64
  num: number;
  name: string; // 乾為天
  short: string; // 乾
  upper: Trigram;
  lower: Trigram;
  lines: number[]; // 下から 6 本
  kw: string;
  text: string;
  question: string;
}

export const HEXAGRAMS: Hexagram[] = RAW.map(([num, name, short, kw, text, question]) => {
  const up = name[0];
  const lo = name[1] === "為" ? name[0] : name[1];
  // 為の卦は「坎為水」のように、1 字目が卦の名(坎)。象(水)は 3 字目
  const upper = name[1] === "為" ? TRIGRAMS[name[2]] : TRIGRAMS[up];
  const lower = name[1] === "為" ? TRIGRAMS[name[2]] : TRIGRAMS[lo];
  if (!upper || !lower) throw new Error(`卦の名が読めません: ${name}`);
  return { id: "h" + num, num, name, short, upper, lower, lines: [...lower.lines, ...upper.lines], kw, text, question };
});
export const HEX_BY_ID: Record<string, Hexagram> = Object.fromEntries(HEXAGRAMS.map((h) => [h.id, h]));

export function hexagramOf(lines: number[]): Hexagram {
  const key = lines.join("");
  const h = HEXAGRAMS.find((x) => x.lines.join("") === key);
  if (!h) throw new Error("卦が見つかりません: " + key);
  return h;
}

export const LINE_POS = ["初爻(始まり・足もと)", "二爻(内の中心)", "三爻(内から外への境目)", "四爻(外の入り口)", "五爻(外の中心・要)", "上爻(終わり・行き過ぎ)"];

/**
 * コインを 3 枚投げて 1 本の爻を決めることを 6 回(下から)。
 * 表 = 3、裏 = 2 の合計: 6 = 老陰(陰・変わる)、7 = 少陽、8 = 少陰、9 = 老陽(陽・変わる)
 */
export function castHexagram(rand: (max: number) => number): { base: Hexagram; moving: number[]; after: Hexagram | null; tosses: number[] } {
  const tosses: number[] = [];
  for (let i = 0; i < 6; i++) tosses.push((rand(2) ? 3 : 2) + (rand(2) ? 3 : 2) + (rand(2) ? 3 : 2));
  const lines = tosses.map((t) => (t === 7 || t === 9 ? 1 : 0));
  const moving = tosses.map((t, i) => (t === 6 || t === 9 ? i : -1)).filter((i) => i >= 0);
  const afterLines = lines.map((l, i) => (moving.includes(i) ? 1 - l : l));
  const base = hexagramOf(lines);
  return { base, moving, after: moving.length ? hexagramOf(afterLines) : null, tosses };
}
